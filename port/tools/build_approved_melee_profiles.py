"""Generate native logical-identity melee profiles from Juan's approved power scale.
Only source headers and an analysis receipt are written; no ISO/shared model is edited.
"""
from pathlib import Path
import csv,json,hashlib,math

SOURCE=Path('F:/BT3-Builds/v05-select/source')
AUDIT=SOURCE/'analysis/v05-roster/damage-audit'
MAX=2147483647
# Logical id: power in billions. Standard-form donors remain authored;
# Gogetto SSJ2/3 progression is explicitly confirmed by Juan.
POWERS={52:5000,53:2250,166:10000,249:4500,172:18000,54:40000,57:100,59:80000,60:5000,147:80,149:40000,
        194:100,201:50,218:48,219:120,
        220:1000,221:2000,222:8000,223:80000,
        225:2900,226:5800,229:23200,230:232000,
        235:5800,238:11600,239:46400,241:464000,294:30}
DONORS={54:172,59:166,60:172,219:216,220:215,221:215,222:215,223:215,
        225:226,226:226,229:229,230:226,235:238,238:238,239:238,241:238}

def main():
    profiles=json.loads((AUDIT/'profiles.json').read_text())
    routes=list(csv.DictReader((AUDIT/'profiles.csv').open(encoding='utf-8-sig')))
    available={(int(r['id']),int(r['costume'])-1):r for r in routes if not int(r['damaged'])}
    # Explicit real costume powers; old host costumes also remain correct if used.
    keys={(cid,0):power for cid,power in POWERS.items()}
    keys.update({(54,1):40000,(59,1):80000,(60,1):1000,
                 (147,1):80,(147,2):80,(147,3):100,
                 (76,2):100,(116,3):30})
    # Super17FP's native stock table exposes four costumes with the same authored power.
    for co in range(4):
        if (201,co) in available:keys[201,co]=50
    keys[164,0]=None;keys[28,3]=None
    rows=[];arrays=[]
    for (cid,co),power in sorted(keys.items()):
        assert (cid,co) in available,(cid,co)
        old=profiles[f'{cid}:{co}:0'];donor=215 if (cid,co)==(59,1) else DONORS.get(cid,cid)
        # A host costume belonging to a promoted fighter uses that costume's own shape.
        ref=profiles[f'{donor}:{0 if donor!=cid else co}:0'];peak=max(ref)
        target=MAX if power is None else power*1000  # Omega80B ->80000 raw max.
        assert 0<target<=MAX
        new=[0 if not v else MAX if power is None else max(1,(ref[i]*target+peak//2)//peak)
             for i,v in enumerate(old)]
        assert len(new)==163 and max(new)==target
        assert all((a==0)==(b==0) for a,b in zip(old,new))
        arrays.append(new)
        defence=1e-6 if power is None else max(1e-6,min(.75,.046875*math.sqrt(80/power)))
        rows.append(dict(id=cid,costume=co,power_B=power,maximum=target,donor=donor,
                         source_melee_max=max(old),defence=defence,
                         first=new[0],name=available[cid,co]['name'],
                         old_sha256=available[cid,co]['profile_sha256']))
    out=['/* Generated by build_approved_melee_profiles.py. Local fights only. */',
         '#ifndef MOD_MELEE_PROFILES_H','#define MOD_MELEE_PROFILES_H',
         'static const int sMdKeys[]={'+','.join(str(r['id']*8+r['costume']) for r in rows)+'};',
         'static const unsigned int sMdProfiles[][163]={']
    out+=['{'+','.join(map(str,a))+'},' for a in arrays]
    out+=['};',
      'static const int sMdPeaks[]={'+','.join(str(x['maximum']) for x in rows)+'};',
      'static const int sMdOldPeaks[]={'+','.join(str(x['source_melee_max']) for x in rows)+'};',
      'static const float sMdDefence[]={'+','.join(format(x['defence'],'.10g')+'f' for x in rows)+'};',
      'static int MD_ProfileIndex(int id,unsigned int costume){int lo=0,hi=(int)(sizeof(sMdKeys)/sizeof(sMdKeys[0])),mid,key;if(id<0||id>=295||costume>7)return -1;key=id*8+(int)costume;while(lo<hi){mid=lo+(hi-lo)/2;if(sMdKeys[mid]<key)lo=mid+1;else hi=mid;}return lo<(int)(sizeof(sMdKeys)/sizeof(sMdKeys[0]))&&sMdKeys[lo]==key?lo:-1;}',
      'static int MD_Offense(int id,unsigned int costume,int value){int row=MD_ProfileIndex(id,costume);if(row<0||value<=0)return value;if(sMdPeaks[row]==2147483647)return 2147483647;return MD_MulDiv(value,sMdPeaks[row],sMdOldPeaks[row]);}',
      'static float MD_Defence(int id,unsigned int costume,float original){int row=MD_ProfileIndex(id,costume);return row<0?original:sMdDefence[row];}',
      'static unsigned int MD_Profile(int id,unsigned int costume,int attack,unsigned int original){',
      ' int lo=0,hi=(int)(sizeof(sMdKeys)/sizeof(sMdKeys[0])),key,mid;',
      ' if(id<0||id>=295||costume>7||attack<0||attack>=163||!original)return original;',
      ' key=id*8+(int)costume;while(lo<hi){mid=lo+(hi-lo)/2;if(sMdKeys[mid]<key)lo=mid+1;else hi=mid;}',
      ' return lo<(int)(sizeof(sMdKeys)/sizeof(sMdKeys[0]))&&sMdKeys[lo]==key?sMdProfiles[lo][attack]:original;',
      '}','#endif','']
    header='\n'.join(out);(SOURCE/'port/include/mod_melee_profiles.h').write_text(header)
    receipt={'status':'GENERATED_APPROVED_SCALE','scope':'local/non-replay, logical identity and costume',
             'max_signed32':MAX,'damage_per_B':1000,'zero_slots_preserved':True,
             'gogetto_progression':'Juan: SSJ2=2xSSJ1; SSJ3=4xSSJ2; SSJ4=10xSSJ3 (232T/464T)',
             'profiles':rows,'header_sha256':hashlib.sha256((SOURCE/'port/include/mod_melee_profiles.h').read_bytes()).hexdigest()}
    (SOURCE/'analysis/codex-user-log-fixes-20261110/approved-profiles.json').write_text(json.dumps(receipt,indent=2))
    print(f'PASS generated {len(rows)} independent identity/costume profiles; maximum signed32; zero fields preserved')

if __name__=='__main__':main()
